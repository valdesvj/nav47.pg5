/* route.h - passage planner for NAV47: geodesic / rhumb / composite legs,
 * waypoint splitting, CSV and NMEA 0183 export.  No malloc; one route_t
 * holds the whole generated plan (~37 KB with ROUTE_MAX_WPT = 512: 100 waypoints, split).
 * Angles in degrees, distances in metres (NM = 1852 m).
 */
#ifndef GEO_ROUTE_H
#define GEO_ROUTE_H

#include <stdint.h>
#include "geodesic.h"
#include "geo_rhumb.h"

#ifndef ROUTE_MAX_WPT
#define ROUTE_MAX_WPT 512
#endif
#define NM 1852.0

typedef enum { SAIL_GEOD = 0, SAIL_RHUMB, SAIL_COMPOSITE } sail_t;
typedef enum { SPLIT_NONE = 0, SPLIT_DIST, SPLIT_LEGS, SPLIT_DLON } split_t;

/* waypoint flags */
#define WPT_USER     0x01   /* entered by the user */
#define WPT_SPLIT    0x02   /* generated by splitting */
#define WPT_VERTEX   0x04   /* composite: start/end of the parallel */

/* segment kinds (of the segment ENDING at this waypoint) */
#define SEG_GEOD  'G'
#define SEG_RHUMB 'R'
#define SEG_PARAL 'P'

typedef struct {
  double lat, lon;     /* lon reduced to [-180,180) */
  double leg_m;        /* along-track distance from previous waypoint */
  double cum_m;        /* cumulative from route start */
  double crs_in;       /* true course arriving here (NAN at start) */
  double crs_out;      /* true course leaving here on the planned track */
  double rl_crs;       /* rhumb course to steer to next waypoint */
  double rl_m;         /* rhumb distance to next waypoint */
  char kind;           /* SEG_* of the segment ending here, ' ' at start */
  uint8_t flags;
} wpt_t;

typedef struct {
  const struct geod_geodesic *g;
  rhumb_t rh;
  wpt_t w[ROUTE_MAX_WPT];
  int n;
  int full;            /* set if waypoints were dropped */
  double lon_u;        /* unrolled longitude of the last waypoint */
} route_t;

enum {
  ROUTE_OK = 0, ROUTE_EFULL = -1, ROUTE_EARG = -2,
  ROUTE_EPOLE = -3, ROUTE_ELIMIT = -4, ROUTE_ECOMP = -5
};

void route_init(route_t *r, const struct geod_geodesic *g);

/* Append one user leg from the last waypoint (or from lat1/lon1 if the
 * route is empty) to lat2/lon2.
 *   sail    SAIL_GEOD, SAIL_RHUMB or SAIL_COMPOSITE
 *   latmax  limiting latitude for SAIL_COMPOSITE (deg, > 0)
 *   split   SPLIT_DIST: param = interval (m)
 *           SPLIT_LEGS: param = number of legs
 *           SPLIT_DLON: param = meridian step (deg); waypoints fall on
 *                       whole multiples (e.g. every 10 deg: 20W, 30W, ...)
 * Composite falls back to a plain geodesic if the limit is not exceeded. */
int route_add_leg(route_t *r, double lat1, double lon1,
                  double lat2, double lon2, sail_t sail, double latmax,
                  split_t split, double param);

/* Fill rl_crs / rl_m (rhumb between consecutive waypoints). */
void route_finish(route_t *r);

/* Vertex (highest latitude) of the geodesic P1->P2, and whether it lies
 * between the two points.  Returns 1 if inside the segment. */
int geod_vertex(const struct geod_geodesic *g, double lat1, double lon1,
                double lat2, double lon2, double *latv, double *lonv,
                double *sv);

/* Output: called once per line, without line terminator. */
typedef void (*route_put_fn)(const char *line, void *ctx);
void route_csv(const route_t *r, route_put_fn put, void *ctx);
void route_nmea(const route_t *r, const char *route_id,
                route_put_fn put, void *ctx);

/* "47 30.52N" / "009 07.10W" style (deg char selectable, 0 = space) */
void geo_fmt_dm(char *buf, double v, int is_lat, char degch);

#endif
