#!/usr/bin/env python3
"""gen_simfont.py OUT.h - a stand-in for the DMCP5 small system font (t20: lib_mono_10x16, cell 11 x 21, baseline 4)
for the PC simulator only, drawn from DejaVu Sans Mono. The calculator uses its own font; only the metrics matter."""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H, B = 11, 21, 4
f = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf', 16)
rows = []
for c in range(32, 128):
    im = Image.new('L', (W, H), 0)
    d = ImageDraw.Draw(im)
    d.text((0, H - B), chr(c), font=f, fill=255, anchor='ls')
    px = im.load()
    for y in range(H):
        rows.append(sum((1 << (W - 1 - x)) for x in range(W) if px[x, y] > 110))
with open(sys.argv[1], 'w') as o:
    o.write('/* generated by test/sim/gen_simfont.py (DejaVu Sans Mono): the simulator stand-in for t20 */\n')
    o.write('#define SIMF_W %d\n#define SIMF_H %d\n#define SIMF_B %d\n' % (W, H, B))
    o.write('static const unsigned short SIMF[96 * %d] = {\n' % H)
    for i in range(0, len(rows), 16):
        o.write('  ' + ', '.join('%d' % r for r in rows[i:i + 16]) + ',\n')
    o.write('};\n')
