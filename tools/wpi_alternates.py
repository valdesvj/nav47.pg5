#!/usr/bin/env python3
"""wpi_alternates.py - the alternate and former port names of NGA's World Port Index (Pub. 150, 24th edition, 2015:
"no copyright claimed under Title 17 U.S.C."), from the PDF's index, into tools/wpi_alternates.csv for gen_ports.py.

    python3 tools/wpi_alternates.py 150-world-port-index.pdf tools/wpi_alternates.csv   (needs pdftotext, poppler)

The index is printed in two columns; an alternate name is "NAME   48275 *" (the star: see the port of that number)."""
import csv, re, subprocess, sys

pdf, out = sys.argv[1], sys.argv[2]
t = subprocess.run(["pdftotext", "-layout", pdf, "-"], capture_output=True, text=True, check=True).stdout.split("\n")
start = next(i for i, l in enumerate(t) if i > len(t) // 2 and re.search(r"\s{2,}\d{5} \*\s*$", l))   # the index, at the back
alts = []
for l in t[start:]:
    for part in (l[:63], l[63:]):                                   # the two columns
        m = re.match(r"^\s*([A-Z][A-Z0-9 '().,/&-]*?[A-Z0-9).])\s{2,}(\d{5}) \*\s*$", part)
        if m and (m[1].strip(), m[2]) not in alts: alts.append((m[1].strip(), m[2]))
with open(out, "w", newline="") as o:
    o.write("# wpi_alternates.csv - GENERATED by tools/wpi_alternates.py from NGA's World Port Index (Pub. 150, 2015), its\n")
    o.write("# index's alternate and former names (US government work, no copyright claimed). index_no,name\n")
    w = csv.writer(o, lineterminator="\n"); w.writerow(["index_no", "name"])
    for name, no in sorted(alts, key=lambda a: (int(a[1]), a[0])): w.writerow([no, name.title()])
print("%s: %d alternate names for %d ports -> %s" % (pdf, len(alts), len({n for _, n in alts}), out))
