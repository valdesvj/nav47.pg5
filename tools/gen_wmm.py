#!/usr/bin/env python3
"""gen_wmm.py - the World Magnetic Model's coefficients (NOAA NCEI / NGA, public domain) into src/wmmdata.c.

    python3 tools/gen_wmm.py WMM.COF src/wmmdata.c

WMM.COF: from https://www.ncei.noaa.gov/products/world-magnetic-model (WMM2025: valid 2025.0 - 2030.0; WMM2030 the
same way). Degree 12: g, h (nT) at the epoch and their secular change gd, hd (nT / year), index n * 13 + m."""
import sys

src, out = sys.argv[1], sys.argv[2]
lines = open(src).read().split("\n")
epoch, name, date = lines[0].split()[:3]
G = {}
for l in lines[1:]:
    f = l.split()
    if len(f) < 6 or f[0].startswith("9999"):
        continue
    n, m = int(f[0]), int(f[1])
    G[(n, m)] = tuple(float(x) for x in f[2:6])
N = 12
assert len(G) == sum(n + 1 for n in range(1, N + 1)), len(G)
def arr(k):
    v = [G.get((n, m), (0, 0, 0, 0))[k] if 1 <= n else 0.0 for n in range(N + 1) for m in range(N + 1)]
    rows = [", ".join("%.1ff" % x for x in v[i:i + 13]) for i in range(0, len(v), 13)]
    return "{\n  " + ",\n  ".join(rows) + "\n}"
with open(out, "w") as o:
    o.write("/* wmmdata.c - GENERATED by tools/gen_wmm.py from %s (%s, %s): do not edit.\n" % (src.split("/")[-1], name, date))
    o.write(" * The World Magnetic Model, NOAA NCEI and the US NGA (public domain). Epoch %s, valid 5 years. */\n" % epoch)
    o.write('#include "wmm.h"\n\n')
    o.write("const double WMM_EPOCH = %s;\nconst char WMM_NAME[] = \"%s\";\n" % (epoch, name))
    for k, nm in enumerate(("WMM_G", "WMM_H", "WMM_GD", "WMM_HD")):
        o.write("const float %s[13 * 13] = %s;\n" % (nm, arr(k)))
print("%s: %s epoch %s, %d coefficients -> %s" % (src, name, epoch, len(G), out))
