#!/usr/bin/env python3
"""gen_airways.py - the US airways for the web page's Flight tab: the FAA's NASR data (the 28-day subscription's CSV:
AWY, FIX, NAV; a work of the US government: no copyright, 17 U.S.C. 105) into web/airways_us.js.

    for k in AWY FIX NAV; do curl -sSfLO https://nfdc.faa.gov/webContent/28DaySub/extra/DD_Mon_YYYY_${k}_CSV.zip; done
    unzip each into AWY/, FIX/, NAV/ of one directory, then:
    python3 tools/gen_airways.py DIR web/airways_us.js

Each airway a chain of its points in order (AWY_SEG_ALT's POINT_SEQ), broken where the FAA marks a gap
(AWY_SEG_GAP_FLAG) and at the border points, which have no position. The points: the fixes (FIX_BASE) and the navaids
(NAV_BASE: a VOR family for the VOR types, an NDB for the NDB ones; of two of one name, the nearer the airway's
previous point). Out: pts "ident|lat|lon" in order of first use; awy "name:i,j,k;i,j|..." (the chains, by index).
"""
import csv, json, math, os, sys

d, out = sys.argv[1], sys.argv[2]
rd = lambda p: list(csv.DictReader(open(os.path.join(d, p), encoding="utf-8-sig", errors="replace")))
fix = {r["FIX_ID"]: (float(r["LAT_DECIMAL"]), float(r["LONG_DECIMAL"])) for r in rd("FIX/FIX_BASE.csv") if r["LAT_DECIMAL"]}
nav = {}
for r in rd("NAV/NAV_BASE.csv"):
    if not r["LAT_DECIMAL"]:
        continue
    fam = "N" if "NDB" in r["NAV_TYPE"] else "V"
    nav.setdefault((r["NAV_ID"], fam), []).append((float(r["LAT_DECIMAL"]), float(r["LONG_DECIMAL"])))
eff = ""
chains = {}
for r in rd("AWY/AWY_SEG_ALT.csv"):
    eff = eff or r["EFF_DATE"]
    chains.setdefault((r["AWY_LOCATION"], r["AWY_ID"]), []).append(r)

def near(cands, prev):
    if not prev or len(cands) == 1:
        return cands[0]
    return min(cands, key=lambda c: (c[0] - prev[0]) ** 2 + ((c[1] - prev[1]) * math.cos(math.radians(c[0]))) ** 2)

pts, idx, awys, lost = [], {}, [], 0
def point(name, typ, prev):
    t = typ.strip()
    if t in ("WP", "RP", "CN") or not t:
        p = fix.get(name)
        key = ("F", name)
    else:
        fam = "N" if "NDB" in t else "V"
        c = nav.get((name, fam)) or nav.get((name, "V" if fam == "N" else "N"))
        p = near(c, prev) if c else None
        key = ("V" + fam, name, round(p[0], 3), round(p[1], 3)) if p else None
    if not p:
        return None, None
    if key not in idx:
        idx[key] = len(pts); pts.append((name, p[0], p[1]))
    return idx[key], p

for (loc, aid), rows in sorted(chains.items()):
    rows.sort(key=lambda r: int(r["POINT_SEQ"]))
    seqs, cur, prev = [], [], None
    for r in rows:
        i, p = point(r["FROM_POINT"], r["FROM_PT_TYPE"], prev)
        if i is None:                                # a border point, or one not found: the chain breaks
            if len(cur) > 1: seqs.append(cur)
            cur, prev = [], None
            if r["FROM_PT_TYPE"].strip(): lost += 1
            continue
        cur.append(i); prev = p
        if r["AWY_SEG_GAP_FLAG"] == "Y":             # no airway from this point to the next
            if len(cur) > 1: seqs.append(cur)
            cur = [i]
    if len(cur) > 1: seqs.append(cur)
    if seqs:
        awys.append(aid + ":" + ";".join(",".join(map(str, s)) for s in seqs))

with open(out, "w", encoding="utf-8") as f:
    f.write("/* airways_us.js - GENERATED by tools/gen_airways.py from the FAA's NASR (28-day subscription, effective %s):\n"
            " * do not edit. A work of the US government (no copyright, 17 U.S.C. 105). %d airways, %d points.\n"
            " * Not for navigation: the Flight tab's planning only. */\n" % (eff, len(awys), len(pts)))
    f.write("const AWY_US = " + json.dumps({"src": "FAA NASR " + eff, "pts": "\n".join("%s|%.5f|%.5f" % p for p in pts),
                                            "awy": "|".join(awys)}, separators=(",", ":")) + ";\n")
print(len(awys), "airways,", len(pts), "points,", lost, "points not found ->", out)
