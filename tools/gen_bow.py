#!/usr/bin/env python3
"""gen_bow.py - your vessel's bow, from a photo taken over it (the helideck, the bridge), for NAV47's BOW page.

    python3 tools/gen_bow.py OUT.c                          # no photo: the drawn bow (the Asiana's lines)
    python3 tools/gen_bow.py OUT.c PHOTO.jpg [--top Y] [--bottom Y] [--left X] [--right X] [--horizon Y]
                             [--threshold 0..255] [--dither] [--png preview.png]

The part of the photo from --top (the bow's stem, its highest point) to --bottom is scaled to the DM42n's width and
put at the bottom of the BOW page, so that the stem sits a little below the drawn horizon; the sea above it stays
NAV47's (the lane, the flags, the platforms). The rows above the deck's edge are see-through: only the ship is kept
(a pixel is the ship when it is darker than --threshold, or with --dither, Floyd-Steinberg). --png shows the result.

make BOW=~/Pictures/asiana_bow.jpg writes build/gen/bowimg.c (never in git: a photo of your ship stays yours).
Copyright (C) 2026 Victor Valdes - GPL-3.0-or-later.
"""
import argparse

W = 400
TOP_ROW = 118          # the stem's row on the LCD (the horizon is row 58)
BOTTOM_ROW = 207


def empty(out):
    with open(out, "w") as f:
        f.write("/* generated by tools/gen_bow.py: no photo, NAV47 draws the bow */\n"
                "const int BOW_W = 0, BOW_H = 0, BOW_Y = 0;\nconst unsigned char BOW_INK[1] = { 0 }, BOW_MASK[1] = { 0 };\n")


def main():
    a = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    a.add_argument("out")
    a.add_argument("photo", nargs="?")
    a.add_argument("--top", type=int, help="the stem's row in the photo (default: 40 %% down)")
    a.add_argument("--bottom", type=int, help="the last row to keep (default: the photo's bottom)")
    a.add_argument("--left", type=int, default=0)
    a.add_argument("--right", type=int)
    a.add_argument("--threshold", type=int, default=110)
    a.add_argument("--dither", action="store_true")
    a.add_argument("--sea", type=int, default=200, help="lighter than this above the deck: the sea (see-through)")
    a.add_argument("--png", help="a preview of the LCD part")
    o = a.parse_args()
    if not o.photo:
        empty(o.out)
        return
    from PIL import Image, ImageOps
    im = ImageOps.exif_transpose(Image.open(o.photo)).convert("L")
    right = o.right or im.width
    top = o.top if o.top is not None else int(im.height * 0.4)
    bottom = o.bottom or im.height
    im = im.crop((o.left, top, right, bottom))
    h = BOTTOM_ROW - TOP_ROW + 1
    im = ImageOps.autocontrast(im.resize((W, h), Image.LANCZOS), cutoff=1)
    px = im.load()
    ink = [[0] * W for _ in range(h)]
    if o.dither:
        err = [[float(px[x, y]) for x in range(W)] for y in range(h)]
        for y in range(h):
            for x in range(W):
                old = err[y][x]
                new = 0 if old < 128 else 255
                ink[y][x] = 1 if new == 0 else 0
                e = old - new
                for dx, dy, k in ((1, 0, 7), (-1, 1, 3), (0, 1, 5), (1, 1, 1)):
                    if 0 <= x + dx < W and y + dy < h:
                        err[y + dy][x + dx] += e * k / 16
    else:
        for y in range(h):
            for x in range(W):
                ink[y][x] = 1 if px[x, y] < o.threshold else 0
    # the mask: the ship, from each column's first dark run down (the sky and the sea above the deck see-through)
    mask = [[0] * W for _ in range(h)]
    for x in range(W):
        on = False
        for y in range(h):
            if not on and (px[x, y] < o.sea and (y + 1 < h and px[x, y + 1] < o.sea)):
                on = True
            mask[y][x] = 1 if on else 0
    def pack(rows):
        out = []
        for r in rows:
            for b in range(0, W, 8):
                v = 0
                for i in range(8):
                    v = (v << 1) | r[b + i]
                out.append(v)
        return out
    with open(o.out, "w") as f:
        f.write("/* generated by tools/gen_bow.py from your photo: never commit it */\n")
        f.write("const int BOW_W = %d, BOW_H = %d, BOW_Y = %d;\n" % (W, h, TOP_ROW))
        for name, rows in (("BOW_INK", ink), ("BOW_MASK", mask)):
            data = pack(rows)
            f.write("const unsigned char %s[%d] = {\n" % (name, len(data)))
            for i in range(0, len(data), 20):
                f.write("  " + ", ".join("0x%02x" % v for v in data[i:i + 20]) + ",\n")
            f.write("};\n")
    if o.png:
        prev = Image.new("RGB", (W, h), (223, 230, 214))
        pp = prev.load()
        for y in range(h):
            for x in range(W):
                if mask[y][x]:
                    pp[x, y] = (30, 34, 32) if ink[y][x] else (223, 230, 214)
                else:
                    pp[x, y] = (190, 205, 225)
        prev.resize((W * 2, h * 2), Image.NEAREST).save(o.png)


if __name__ == "__main__":
    main()
