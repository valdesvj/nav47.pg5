#!/usr/bin/env python3
"""gen_airports.py - the world's airports for the web page's Flight tab, and the helicopter bases: OurAirports' data
(ourairports.com, public domain: "all of the data is in the public domain") into web/airports.js.

    curl -sSfLO https://davidmegginson.github.io/ourairports-data/airports.csv
    python3 tools/gen_airports.py airports.csv web/airports.js

Kept: the large and medium airports (open), and the heliports of the countries in HELI_CC (the field's bases: Saudi
Arabia's Aramco heliports). A line: ident|IATA|name|city|country|lat|lon|kind (L large, M medium, H heliport).
"""
import csv, json, sys

HELI_CC = {"SA", "BH", "KW", "QA", "AE"}
src, out = sys.argv[1], sys.argv[2]
rows = []
for r in csv.DictReader(open(src, encoding="utf-8")):
    t = r["type"]
    kind = {"large_airport": "L", "medium_airport": "M"}.get(t) or ("H" if t == "heliport" and r["iso_country"] in HELI_CC else None)
    if not kind:
        continue
    clean = lambda s: s.replace("|", " ").replace("\n", " ").strip()
    rows.append("|".join([clean(r["ident"]), clean(r["iata_code"]), clean(r["name"]), clean(r["municipality"]), r["iso_country"],
                          "%.5f" % float(r["latitude_deg"]), "%.5f" % float(r["longitude_deg"]), kind]))
rows.sort(key=lambda l: l.split("|")[2].lower())
with open(out, "w", encoding="utf-8") as f:
    f.write("/* airports.js - GENERATED by tools/gen_airports.py from OurAirports' airports.csv: do not edit.\n"
            " * OurAirports (ourairports.com), public domain: %d airports (large, medium) and the Gulf's heliports.\n"
            " * ident|IATA|name|city|country|lat|lon|kind (L large, M medium, H heliport) */\n" % len(rows))
    f.write("const AIRPORTS = " + json.dumps("\n".join(rows), ensure_ascii=False) + ";\n")
print(len(rows), "airports into", out)
