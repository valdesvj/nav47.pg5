#!/usr/bin/env python3
"""gen_sealanes.py - the sea lanes for the web page's Ports tab: Eurostat SeaRoute's maritime network (marnet,
EUPL-1.2; from Oak Ridge National Laboratory's Global Shipping Lane Network, enriched with AIS) into web/sealanes.js.

    python3 tools/gen_sealanes.py marnet_plus_20km.gpkg web/sealanes.js

marnet_plus_20km.gpkg: https://github.com/eurostat/searoute (modules/core/src/main/resources/marnet/). Every segment
becomes an edge between two nodes; its length the WGS84 geodesic (geographiclib), metres. The passages SeaRoute tags
(Suez, Panama, the straits, the Arctic passages) keep their tag, so the page can avoid them. For planning, not for
navigation."""
import base64, json, sqlite3, struct, sys
from geographiclib.geodesic import Geodesic

PASS = ["", "suez", "panama", "malacca", "gibraltar", "dover", "bering", "magellan", "babelmandeb", "kiel", "corinth",
        "northwest", "northeast"]
src, out = sys.argv[1], sys.argv[2]
db = sqlite3.connect(src)
nodes, index, edges = [], {}, []

def node(lon, lat):
    lon = ((lon + 180) % 360) - 180 if abs(lon) > 180 else lon
    k = (round(lat * 1e6), round(lon * 1e6))
    if k not in index:
        index[k] = len(nodes); nodes.append(k)
    return index[k]

def lines(g):                                   # a GeoPackage geometry blob: its WKB LineString(s), [(lon, lat)...]
    env = (g[3] >> 1) & 7
    off = 8 + [0, 32, 48, 48, 64][env]
    def wkb(o):
        bo = '<' if g[o] == 1 else '>'
        t = struct.unpack(bo + 'I', g[o + 1:o + 5])[0] % 1000
        if t == 2:
            n = struct.unpack(bo + 'I', g[o + 5:o + 9])[0]
            pts = [struct.unpack(bo + 'dd', g[o + 9 + 16 * i:o + 25 + 16 * i]) for i in range(n)]
            return [pts], o + 9 + 16 * n
        if t == 5:
            n = struct.unpack(bo + 'I', g[o + 5:o + 9])[0]; o += 9; res = []
            for _ in range(n):
                l, o = wkb(o); res += l
            return res, o
        raise ValueError("geometry type %d" % t)
    return wkb(off)[0]

G = Geodesic.WGS84
for g, ps in db.execute("select geometry, pass from type"):
    code = PASS.index(ps) if ps in PASS else 0
    for line in lines(g):
        for (x0, y0), (x1, y1) in zip(line, line[1:]):
            a, b = node(x0, y0), node(x1, y1)
            if a == b:
                continue
            s = G.Inverse(y0, x0, y1, x1)["s12"]
            edges.append((a, b, int(round(s)), code))

def b64(fmt, vals):
    return base64.b64encode(struct.pack("<%d%s" % (len(vals), fmt), *vals)).decode()
nflat = [v for k in nodes for v in k]
with open(out, "w") as o:
    o.write("/* sealanes.js - GENERATED by tools/gen_sealanes.py from %s: do not edit.\n" % src.split("/")[-1])
    o.write(" * Eurostat SeaRoute's maritime network (EUPL-1.2), from Oak Ridge National Laboratory's Global Shipping Lane\n")
    o.write(" * Network (2000) and AIS. %d nodes, %d edges. For planning, not for navigation. */\n" % (len(nodes), len(edges)))
    o.write("const SEALANES = %s;\n" % json.dumps({
        "pass": PASS, "nodes": b64("i", nflat),
        "edges": b64("I", [v for e in edges for v in e[:3]]), "codes": b64("B", [e[3] for e in edges])}))
print("%s: %d nodes, %d edges, %d tagged -> %s" % (src, len(nodes), len(edges), sum(1 for e in edges if e[3]), out))
